"""Generate reference docs from the real artefacts (never hand-maintained):

* docs/data-dictionary.md  - every Delta table in the lakehouse: columns, types, row counts (delta-rs)
* docs/data-contracts.md   - event envelope + payload contract per topic (schemas/contracts.py)

    python scripts/generate_docs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TABLE_NOTES = {
    "bronze": "Raw, append-only. Duplicates preserved. Partitioned by `processing_date`.",
    "silver": "Cleaned, conformed, deduplicated. MERGE-maintained. PII masked.",
    "gold": "Business-ready star schema and marts (see architecture/data-model.md for grains).",
    "audit": "Control-plane tables: data-quality results, Gold watermarks, reconciliation.",
    "quarantine": "Rejected records with reasons, kept for investigation and replay.",
}


def data_dictionary() -> str:
    from deltalake import DeltaTable

    from pipelines.common.storage import delta_rs_storage_options

    sys.path.insert(0, str(ROOT / "scripts"))
    from lakehouse_status import list_tables

    opts = delta_rs_storage_options()
    lines = [
        "# Data dictionary",
        "",
        "_Generated by `scripts/generate_docs.py` from the live Delta tables (schemas, partitioning and row "
        "counts at generation time). Do not edit by hand._",
        "",
    ]
    for layer in ("bronze", "silver", "gold", "audit", "quarantine"):
        names = list_tables(layer)
        if not names:
            continue
        lines += [f"## {layer.capitalize()}", "", TABLE_NOTES[layer], ""]
        for name in names:
            try:
                dt = DeltaTable(f"s3://lakehouse/{layer}/{name}", storage_options=opts)
            except Exception:  # noqa: S112 - not a Delta table
                continue
            actions = dt.get_add_actions(flatten=True)
            rows = (
                sum(int(x) for x in actions.column("num_records").to_pylist())
                if "num_records" in actions.schema.names
                else 0
            )
            meta = dt.metadata()
            parts = ", ".join(meta.partition_columns) or "-"
            lines += [
                f"### `{layer}.{name}`",
                "",
                f"Rows: **{rows:,}** · Partitioned by: `{parts}` · Delta version: {dt.version()}"
                + (f" · {meta.description}" if meta.description else ""),
                "",
                "| Column | Type | Nullable |",
                "|---|---|---|",
            ]
            for field in dt.schema().fields:
                lines.append(f"| `{field.name}` | {field.type} | {'yes' if field.nullable else 'no'} |")
            lines.append("")
    return "\n".join(lines).replace('PrimitiveType("', "").replace('")', "") + "\n"


def data_contracts() -> str:
    from pipelines.common.config import load_topics
    from schemas.contracts import EVENT_TYPES, PAYLOADS

    lines = [
        "# Data contracts",
        "",
        "_Payload tables are generated by `scripts/generate_docs.py` from `schemas/contracts.py`, the single "
        "source of truth that also produces the Avro (`schemas/avro`) and JSON Schema (`schemas/json`) files._",
        "",
        "## Contract rules",
        "",
        "| Rule | Enforcement |",
        "|---|---|",
        "| Every event uses the standard envelope | Avro record `<Entity>Event`; producers validate with fastavro before "
        "sending |",
        "| Schemas are registered per topic (`<topic>-value`, TopicNameStrategy) | `ingestion.kafka_producers.admin "
        "bootstrap`; producers run with `auto.register.schemas=false` |",
        "| Compatibility mode **BACKWARD** | Schema Registry rejects breaking changes; CI `check-compat` gate |",
        "| Allowed change: add an optional field with a default; widen int→long | Consumers decode old and new events "
        "(writer→reader schema resolution in Bronze) |",
        "| Breaking change (remove / rename / retype a required field) | New topic version (`ecommerce.orders.v2`), "
        "dual-publish during migration |",
        "| Timestamps are UTC, `timestamp-millis` | Contract type |",
        "| Monetary amounts are decimals in the order currency, rounded to minor units | Producer + Silver "
        "`total_reconciles` check |",
        "| PII (names, e-mail) only in `customers` events | Masked/hashed in Silver; Bronze access restricted |",
        "| Invalid events go to `ecommerce.dead-letter` with the error | Producer validation + Bronze decode |",
        "",
        "## Envelope",
        "",
        "| Field | Type | Description |",
        "|---|---|---|",
        "| `event_id` | string | Globally unique event id (UUID); dedup key |",
        "| `event_type` | string | Business event name (allowed values per topic below) |",
        "| `event_version` | int | Payload contract version |",
        "| `event_timestamp` | timestamp-millis | Business event time (UTC) |",
        "| `source_system` | string | Emitting system |",
        "| `correlation_id` | string | Ties all events of a journey / order together |",
        "| `payload` | record | Entity payload (below) |",
        "",
    ]
    by_entity = {t["entity"]: t for t in load_topics()}
    for entity, fields in PAYLOADS.items():
        t = by_entity[entity]
        lines += [
            f"## `{t['name']}` ({entity})",
            "",
            f"{t['description']}  ",
            f"Key: `{t['key']}` · Partitions: {t['partitions']} local / {t['partitions_full']} full scale · "
            f"Retention: {int(t['retention_ms']) // 86_400_000} days  ",
            "Event types: " + ", ".join(f"`{e}`" for e in EVENT_TYPES[entity]),
            "",
            "| Field | Type | Required | Description |",
            "|---|---|---|---|",
        ]
        lines += [
            f"| `{n}` | {ty} | {'no' if nullable else 'yes'} | {doc} |" for n, ty, nullable, doc in fields
        ]
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    (ROOT / "docs" / "data-contracts.md").write_bytes(data_contracts().encode())
    print("wrote docs/data-contracts.md")
    (ROOT / "docs" / "data-dictionary.md").write_bytes(data_dictionary().encode())
    print("wrote docs/data-dictionary.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
